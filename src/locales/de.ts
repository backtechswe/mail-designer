/**
 * German.
 *
 * Two conventions this follows. **Du, not Sie** — every design tool people compare this with
 * (Figma, Notion, Linear) addresses its user informally in German, and a mail editor that says
 * "Sie" reads like online banking. And **German runs longer than English**: the labels wrap,
 * which the layout handles, but hints were shortened where the German said the same thing in
 * more words rather than translated word for word.
 *
 * Checked against what the industry actually writes: *Preheader* stays untranslated, because
 * that is the word Brevo's German editor, rapidmail and the German Mailchimp material all use —
 * *Vorschautext* is a gloss, not the label. *Innenabstand* for padding matches localised design
 * tooling.
 *
 * *Trennlinie* and *Abstandhalter* are the block names Stripo's German uses, and the second
 * of those fixed a real bug: *Abstand* was the spacer block *and* the column gap, two controls
 * with one word.
 *
 * One deliberate departure: the German email world says *Merge-Tag* for a data field. This
 * says *Datenfeld*, for the same reason the English says "data field" and not "merge field" —
 * it is the jargon, not the thing. *Platzhalter* would have been the other plain option.
 */
